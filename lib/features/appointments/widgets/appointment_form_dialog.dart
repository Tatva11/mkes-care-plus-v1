import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../core/theme/app_colors.dart';
import '../../../core/theme/app_spacing.dart';
import '../../../core/theme/app_typography.dart';
import '../../../shared/widgets/mkes_primary_button.dart';
import '../../../shared/widgets/mkes_text_field.dart';
import '../../admin/models/user_profile.dart';
import '../../admin/providers/users_provider.dart';
import '../../patients/models/patient_model.dart';
import '../../patients/providers/patients_provider.dart';
import '../../patients/widgets/patient_form_dialog.dart';
import '../models/appointment_model.dart';
import '../providers/appointment_provider.dart';

class AppointmentFormDialog extends ConsumerStatefulWidget {
  const AppointmentFormDialog({
    super.key,
    this.initialDate,
    this.initialPatientId,
    this.initialPatientName,
    this.initialAppointmentType = 'regular',
  });

  final DateTime? initialDate;
  final String? initialPatientId;
  final String? initialPatientName;
  final String initialAppointmentType;

  @override
  ConsumerState<AppointmentFormDialog> createState() =>
      _AppointmentFormDialogState();
}

class _AppointmentFormDialogState extends ConsumerState<AppointmentFormDialog> {
  final _formKey = GlobalKey<FormState>();

  String? _selectedPatientId;
  String? _selectedPatientName;
  String? _selectedPatientNumber;
  String _selectedDepartment = 'eye';
  String? _selectedDoctorId;
  String? _selectedDoctorName;
  String? _selectedDoctorSpecialty;
  late DateTime _selectedDate;
  TimeOfDay _selectedTime = const TimeOfDay(hour: 9, minute: 0);
  late String _selectedType;
  late final TextEditingController _roomController;
  late final TextEditingController _notesController;

  bool _isLoading = false;

  @override
  void initState() {
    super.initState();
    _selectedDate = widget.initialDate ?? DateTime.now();
    _selectedType = widget.initialAppointmentType;
    _selectedPatientId = widget.initialPatientId;
    _selectedPatientName = widget.initialPatientName;

    _roomController = TextEditingController(
      text: _selectedDepartment == 'dental' ? 'Dental Suite 1' : 'Room 102',
    );
    _notesController = TextEditingController();
  }

  @override
  void dispose() {
    _roomController.dispose();
    _notesController.dispose();
    super.dispose();
  }

  String _formatTimeOfDay(TimeOfDay time) {
    final hour = time.hour.toString().padLeft(2, '0');
    final minute = time.minute.toString().padLeft(2, '0');
    return '$hour:$minute:00';
  }

  String _formatDisplayTime(TimeOfDay time) {
    final hour = time.hourOfPeriod == 0 ? 12 : time.hourOfPeriod;
    final minute = time.minute.toString().padLeft(2, '0');
    final period = time.period == DayPeriod.am ? 'AM' : 'PM';
    return '$hour:$minute $period';
  }

  Future<void> _submit() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() => _isLoading = true);

    try {
      final newAppointment = AppointmentModel(
        id: '', // Will be generated by Supabase (UUID)
        patientId: _selectedPatientId,
        patientName: _selectedPatientName ?? 'Walk-in Patient',
        patientNumber: _selectedPatientNumber ?? 'Unknown ID',
        department: _selectedDepartment,
        doctorId: _selectedDoctorId,
        doctorName: _selectedDoctorName,
        specialty: _selectedDoctorSpecialty,
        appointmentDate: _selectedDate,
        appointmentTime: _formatTimeOfDay(_selectedTime),
        appointmentType: _selectedType,
        room: _roomController.text.trim().isNotEmpty
            ? _roomController.text.trim()
            : (_selectedDepartment == 'dental' ? 'Dental Suite 1' : 'Room 102'),
        status: _selectedType == 'walk_in' ? 'waiting' : 'scheduled',
        notes: _notesController.text.trim().isNotEmpty
            ? _notesController.text.trim()
            : null,
        aiBooked: false,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      await ref
          .read(appointmentsNotifierProvider.notifier)
          .createAppointment(newAppointment);

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            backgroundColor: AppColors.primaryContainer,
            content: Row(
              children: [
                const Icon(Icons.check_circle, color: Colors.white),
                const SizedBox(width: AppSpacing.xs),
                Expanded(
                  child: Text(
                    'Appointment for ${_selectedPatientName ?? "Patient"} booked successfully!',
                    style: const TextStyle(color: Colors.white),
                  ),
                ),
              ],
            ),
          ),
        );
        Navigator.of(context).pop(true);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to create appointment: $e'),
            backgroundColor: AppColors.error,
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isLoading = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final patientsAsync = ref.watch(patientsProvider);
    final usersAsync = ref.watch(usersProvider);
    final screenWidth = MediaQuery.sizeOf(context).width;
    final screenHeight = MediaQuery.sizeOf(context).height;
    final viewInsets = MediaQuery.viewInsetsOf(context);

    final dialogMaxWidth = (screenWidth - 32).clamp(280.0, 560.0);
    final dialogMaxHeight =
        (screenHeight - viewInsets.bottom - 60).clamp(320.0, 720.0);

    return Dialog(
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AppSpacing.radiusXl),
      ),
      insetPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 24),
      child: ConstrainedBox(
        constraints: BoxConstraints(
          maxWidth: dialogMaxWidth,
          maxHeight: dialogMaxHeight,
        ),
        child: Form(
          key: _formKey,
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              // Dialog Header
              Container(
                padding: const EdgeInsets.all(AppSpacing.md),
                decoration: const BoxDecoration(
                  border: Border(
                    bottom: BorderSide(color: AppColors.outlineVariant),
                  ),
                ),
                child: Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Row(
                      children: [
                        Container(
                          padding: const EdgeInsets.all(8),
                          decoration: BoxDecoration(
                            color: AppColors.primaryContainer
                                .withValues(alpha: 0.15),
                            borderRadius:
                                BorderRadius.circular(AppSpacing.radiusSm),
                          ),
                          child: const Icon(
                            Icons.calendar_month,
                            color: AppColors.primaryContainer,
                            size: 20,
                          ),
                        ),
                        const SizedBox(width: AppSpacing.sm),
                        Text(
                          'New Appointment',
                          style: AppTypography.headlineMd,
                        ),
                      ],
                    ),
                    IconButton(
                      icon: const Icon(Icons.close, size: 20),
                      onPressed: () => Navigator.of(context).pop(),
                      color: AppColors.onSurfaceVariant,
                    ),
                  ],
                ),
              ),

              // Form Body
              Flexible(
                child: SingleChildScrollView(
                  padding: const EdgeInsets.all(AppSpacing.md),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      // 1. Patient Selection
                      Text(
                        'Patient Information',
                        style: AppTypography.labelCaps
                            .copyWith(color: AppColors.primary),
                      ),
                      const SizedBox(height: AppSpacing.xs),
                      patientsAsync.when(
                        loading: () => const LinearProgressIndicator(),
                        error: (e, _) => Text('Error loading patients: $e'),
                        data: (patients) {
                          // If initial patient was provided, match it
                          if (_selectedPatientId != null &&
                              _selectedPatientName == null) {
                            final match = patients
                                .where((p) => p.id == _selectedPatientId)
                                .firstOrNull;
                            if (match != null) {
                              _selectedPatientName = match.name;
                              _selectedPatientNumber = match.patientNumber;
                            }
                          }

                          return Column(
                            crossAxisAlignment: CrossAxisAlignment.stretch,
                            children: [
                              DropdownButtonFormField<String?>(
                                initialValue: _selectedPatientId,
                                decoration: InputDecoration(
                                  labelText: 'Select Patient *',
                                  prefixIcon:
                                      const Icon(Icons.person_search_outlined),
                                  border: OutlineInputBorder(
                                    borderRadius: BorderRadius.circular(
                                        AppSpacing.radiusMd),
                                  ),
                                ),
                                items: [
                                  ...patients.map(
                                    (PatientModel p) =>
                                        DropdownMenuItem<String?>(
                                      value: p.id,
                                      child: Text(
                                        '${p.name} (${p.patientNumber})',
                                        overflow: TextOverflow.ellipsis,
                                      ),
                                    ),
                                  ),
                                ],
                                validator: (val) {
                                  if (val == null || val.isEmpty) {
                                    return 'Please select a patient';
                                  }
                                  return null;
                                },
                                onChanged: (val) {
                                  setState(() {
                                    _selectedPatientId = val;
                                    final match = patients
                                        .where((p) => p.id == val)
                                        .firstOrNull;
                                    if (match != null) {
                                      _selectedPatientName = match.name;
                                      _selectedPatientNumber =
                                          match.patientNumber;
                                      if (match.department != null &&
                                          (match.department == 'eye' ||
                                              match.department == 'dental')) {
                                        _selectedDepartment = match.department!;
                                      }
                                    }
                                  });
                                },
                              ),
                              Align(
                                alignment: Alignment.centerRight,
                                child: TextButton.icon(
                                  onPressed: () async {
                                    final created =
                                        await showDialog<PatientModel>(
                                      context: context,
                                      builder: (_) => PatientFormDialog(
                                        initialDepartment: _selectedDepartment,
                                      ),
                                    );
                                    if (created == null || !mounted) return;
                                    setState(() {
                                      _selectedPatientId = created.id;
                                      _selectedPatientName = created.name;
                                      _selectedPatientNumber =
                                          created.patientNumber;
                                      if (created.department != null) {
                                        _selectedDepartment =
                                            created.department!;
                                        _roomController.text =
                                            created.department == 'dental'
                                                ? 'Dental Suite 1'
                                                : 'Room 102';
                                      }
                                    });
                                  },
                                  icon: const Icon(Icons.person_add_alt_1),
                                  label: const Text('+ New Patient'),
                                ),
                              ),
                            ],
                          );
                        },
                      ),

                      const SizedBox(height: AppSpacing.md),

                      // 2. Department & Appointment Type
                      Row(
                        children: [
                          Expanded(
                            child: DropdownButtonFormField<String>(
                              initialValue: _selectedDepartment,
                              decoration: InputDecoration(
                                labelText: 'Department *',
                                prefixIcon:
                                    const Icon(Icons.local_hospital_outlined),
                                border: OutlineInputBorder(
                                  borderRadius: BorderRadius.circular(
                                      AppSpacing.radiusMd),
                                ),
                              ),
                              items: const [
                                DropdownMenuItem(
                                  value: 'eye',
                                  child: Text('Eye Clinic'),
                                ),
                                DropdownMenuItem(
                                  value: 'dental',
                                  child: Text('Dental Clinic'),
                                ),
                              ],
                              onChanged: (val) {
                                if (val != null) {
                                  setState(() {
                                    _selectedDepartment = val;
                                    _roomController.text = val == 'dental'
                                        ? 'Dental Suite 1'
                                        : 'Room 102';
                                  });
                                }
                              },
                            ),
                          ),
                          const SizedBox(width: AppSpacing.md),
                          Expanded(
                            child: DropdownButtonFormField<String>(
                              initialValue: _selectedType,
                              decoration: InputDecoration(
                                labelText: 'Type *',
                                prefixIcon:
                                    const Icon(Icons.medical_services_outlined),
                                border: OutlineInputBorder(
                                  borderRadius: BorderRadius.circular(
                                      AppSpacing.radiusMd),
                                ),
                              ),
                              items: const [
                                DropdownMenuItem(
                                  value: 'regular',
                                  child: Text('Regular Visit'),
                                ),
                                DropdownMenuItem(
                                  value: 'walk_in',
                                  child: Text('Walk-in'),
                                ),
                                DropdownMenuItem(
                                  value: 'follow_up',
                                  child: Text('Follow-up'),
                                ),
                              ],
                              onChanged: (val) {
                                if (val != null) {
                                  setState(() => _selectedType = val);
                                }
                              },
                            ),
                          ),
                        ],
                      ),

                      const SizedBox(height: AppSpacing.md),

                      // 3. Attending Doctor / Clinical Staff
                      Text(
                        'Clinical Staff Assignment',
                        style: AppTypography.labelCaps
                            .copyWith(color: AppColors.primary),
                      ),
                      const SizedBox(height: AppSpacing.xs),
                      usersAsync.when(
                        loading: () => const LinearProgressIndicator(),
                        error: (e, _) => Text('Error loading staff: $e'),
                        data: (users) {
                          final staffMembers =
                              users.where((u) => u.isActive).toList();

                          return DropdownButtonFormField<String?>(
                            initialValue: _selectedDoctorId,
                            decoration: InputDecoration(
                              labelText: 'Attending Doctor / Specialist',
                              prefixIcon: const Icon(Icons.person_pin_outlined),
                              border: OutlineInputBorder(
                                borderRadius:
                                    BorderRadius.circular(AppSpacing.radiusMd),
                              ),
                            ),
                            items: [
                              const DropdownMenuItem<String?>(
                                value: null,
                                child: Text('Unassigned (General Queue)'),
                              ),
                              ...staffMembers.map(
                                (UserProfile u) => DropdownMenuItem<String?>(
                                  value: u.id,
                                  child: Text(
                                    '${u.fullName} (${u.designation ?? u.role})',
                                    overflow: TextOverflow.ellipsis,
                                  ),
                                ),
                              ),
                            ],
                            onChanged: (val) {
                              setState(() {
                                _selectedDoctorId = val;
                                final match = staffMembers
                                    .where((u) => u.id == val)
                                    .firstOrNull;
                                if (match != null) {
                                  _selectedDoctorName = match.fullName;
                                  _selectedDoctorSpecialty = match.designation;
                                } else {
                                  _selectedDoctorName = null;
                                  _selectedDoctorSpecialty = null;
                                }
                              });
                            },
                          );
                        },
                      ),

                      const SizedBox(height: AppSpacing.md),

                      // 4. Date & Time Selection
                      Row(
                        children: [
                          Expanded(
                            child: InkWell(
                              onTap: () async {
                                final picked = await showDatePicker(
                                  context: context,
                                  initialDate: _selectedDate,
                                  firstDate: DateTime.now()
                                      .subtract(const Duration(days: 30)),
                                  lastDate: DateTime.now()
                                      .add(const Duration(days: 365)),
                                );
                                if (picked != null) {
                                  setState(() => _selectedDate = picked);
                                }
                              },
                              child: InputDecorator(
                                decoration: InputDecoration(
                                  labelText: 'Date *',
                                  prefixIcon:
                                      const Icon(Icons.calendar_today_outlined),
                                  border: OutlineInputBorder(
                                    borderRadius: BorderRadius.circular(
                                        AppSpacing.radiusMd),
                                  ),
                                ),
                                child: Text(
                                  '${_selectedDate.day}/${_selectedDate.month}/${_selectedDate.year}',
                                  style: AppTypography.bodyMd,
                                ),
                              ),
                            ),
                          ),
                          const SizedBox(width: AppSpacing.md),
                          Expanded(
                            child: InkWell(
                              onTap: () async {
                                final picked = await showTimePicker(
                                  context: context,
                                  initialTime: _selectedTime,
                                );
                                if (picked != null) {
                                  setState(() => _selectedTime = picked);
                                }
                              },
                              child: InputDecorator(
                                decoration: InputDecoration(
                                  labelText: 'Time Slot *',
                                  prefixIcon:
                                      const Icon(Icons.access_time_outlined),
                                  border: OutlineInputBorder(
                                    borderRadius: BorderRadius.circular(
                                        AppSpacing.radiusMd),
                                  ),
                                ),
                                child: Text(
                                  _formatDisplayTime(_selectedTime),
                                  style: AppTypography.bodyMd,
                                ),
                              ),
                            ),
                          ),
                        ],
                      ),

                      const SizedBox(height: AppSpacing.md),

                      // 5. Room & Clinical Notes
                      MkesTextField(
                        controller: _roomController,
                        label: 'Room / Suite',
                        prefixIcon: Icons.meeting_room_outlined,
                      ),

                      const SizedBox(height: AppSpacing.md),

                      MkesTextField(
                        controller: _notesController,
                        label: 'Clinical Notes / Chief Complaint',
                        hintText:
                            'e.g., Routine vision screening, IOP check, follow-up',
                        maxLines: 3,
                        prefixIcon: Icons.note_alt_outlined,
                      ),
                    ],
                  ),
                ),
              ),

              // Dialog Footer
              Container(
                padding: const EdgeInsets.all(AppSpacing.md),
                decoration: const BoxDecoration(
                  border: Border(
                    top: BorderSide(color: AppColors.outlineVariant),
                  ),
                ),
                child: Row(
                  children: [
                    TextButton(
                      onPressed:
                          _isLoading ? null : () => Navigator.of(context).pop(),
                      child: const Text('Cancel'),
                    ),
                    const SizedBox(width: AppSpacing.md),
                    if (_isLoading)
                      const Expanded(
                        child: Center(child: CircularProgressIndicator()),
                      )
                    else
                      Expanded(
                        child: MkesPrimaryButton(
                          label: 'Book Appointment',
                          onPressed: _submit,
                        ),
                      ),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}
