import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';

import '../../../core/theme/app_breakpoints.dart';
import '../../../core/theme/app_colors.dart';
import '../../../core/theme/app_spacing.dart';
import '../../../core/theme/app_typography.dart';
import '../../../shared/widgets/adaptive_dialog_shell.dart';
import '../../../shared/widgets/responsive_form_row.dart';
import '../../patients/models/patient_model.dart';
import '../../patients/providers/patients_provider.dart';
import '../models/dental_lab_model.dart';
import '../providers/dental_lab_provider.dart';

class DentalLabFormDialog extends ConsumerStatefulWidget {
  const DentalLabFormDialog({
    super.key,
    this.initialCase,
    this.preselectedPatient,
  });

  final DentalLabModel? initialCase;
  final PatientModel? preselectedPatient;

  @override
  ConsumerState<DentalLabFormDialog> createState() => _DentalLabFormDialogState();
}

class _DentalLabFormDialogState extends ConsumerState<DentalLabFormDialog> {
  final _formKey = GlobalKey<FormState>();

  PatientModel? _selectedPatient;
  late TextEditingController _caseNumberController;
  late TextEditingController _caseTypeController;
  late TextEditingController _remarksController;
  late TextEditingController _patientSearchController;

  late DateTime _sentDate;
  DateTime? _readyDate;
  DateTime? _deliveredDate;

  bool _isSaving = false;
  String? _errorMessage;

  static const List<String> _suggestedCaseTypes = [
    'Zirconia Crown',
    'PFM Crown',
    '3-Unit Bridge',
    'Full Upper Denture',
    'Full Lower Denture',
    'Partial Acrylic Denture',
    'Cast Partial Denture',
    'Implant Abutment',
    'Ceramic Veneer',
    'Night Guard / Occlusal Splint',
    'Orthodontic Retainer',
  ];

  @override
  void initState() {
    super.initState();
    final initial = widget.initialCase;

    _selectedPatient = widget.preselectedPatient ?? initial?.patient;

    _caseNumberController = TextEditingController(text: initial?.caseNumber ?? '');
    _caseTypeController = TextEditingController(text: initial?.caseType ?? '');
    _remarksController = TextEditingController(text: initial?.remarks ?? '');
    _patientSearchController = TextEditingController(
      text: _selectedPatient != null ? '${_selectedPatient!.name} (${_selectedPatient!.patientNumber})' : '',
    );

    _sentDate = initial?.sentDate ?? DateTime.now();
    _readyDate = initial?.readyDate;
    _deliveredDate = initial?.deliveredDate;

    // Auto-generate case number if creating new case and field is empty
    if (initial == null && _caseNumberController.text.isEmpty) {
      _loadAutoGeneratedCaseNumber();
    }
  }

  Future<void> _loadAutoGeneratedCaseNumber() async {
    try {
      final repo = ref.read(dentalLabRepositoryProvider);
      final nextNum = await repo.generateNextCaseNumber();
      if (mounted && _caseNumberController.text.isEmpty) {
        setState(() {
          _caseNumberController.text = nextNum;
        });
      }
    } catch (_) {
      // Non-critical: User can type manually
    }
  }

  @override
  void dispose() {
    _caseNumberController.dispose();
    _caseTypeController.dispose();
    _remarksController.dispose();
    _patientSearchController.dispose();
    super.dispose();
  }

  Future<void> _pickSentDate() async {
    final picked = await showDatePicker(
      context: context,
      initialDate: _sentDate,
      firstDate: DateTime(2020),
      lastDate: DateTime.now().add(const Duration(days: 365)),
    );
    if (picked != null && mounted) {
      setState(() {
        _sentDate = picked;
        // Verify ready/delivered date consistency
        if (_readyDate != null && _readyDate!.isBefore(_sentDate)) {
          _readyDate = _sentDate;
        }
        if (_deliveredDate != null && _deliveredDate!.isBefore(_sentDate)) {
          _deliveredDate = _sentDate;
        }
      });
    }
  }

  Future<void> _pickReadyDate() async {
    final picked = await showDatePicker(
      context: context,
      initialDate: _readyDate ?? _sentDate,
      firstDate: _sentDate,
      lastDate: DateTime.now().add(const Duration(days: 365)),
    );
    if (picked != null && mounted) {
      setState(() {
        _readyDate = picked;
        if (_deliveredDate != null && _deliveredDate!.isBefore(_readyDate!)) {
          _deliveredDate = _readyDate;
        }
      });
    }
  }

  Future<void> _pickDeliveredDate() async {
    final earliest = _readyDate ?? _sentDate;
    final picked = await showDatePicker(
      context: context,
      initialDate: _deliveredDate ?? earliest,
      firstDate: earliest,
      lastDate: DateTime.now().add(const Duration(days: 365)),
    );
    if (picked != null && mounted) {
      setState(() {
        _deliveredDate = picked;
      });
    }
  }

  Future<void> _save() async {
    setState(() {
      _errorMessage = null;
    });

    if (!_formKey.currentState!.validate()) {
      return;
    }

    if (_selectedPatient == null) {
      setState(() {
        _errorMessage = 'Please select a valid patient.';
      });
      return;
    }

    if (_selectedPatient!.department?.toLowerCase() != 'dental') {
      setState(() {
        _errorMessage =
            'Patient "${_selectedPatient!.name}" is registered in "${_selectedPatient!.department ?? 'unknown'}" department. Dental Lab cases are strictly for Dental department patients.';
      });
      return;
    }

    final dateError = DentalLabModel.validateDates(
      sentDate: _sentDate,
      readyDate: _readyDate,
      deliveredDate: _deliveredDate,
    );
    if (dateError != null) {
      setState(() {
        _errorMessage = dateError;
      });
      return;
    }

    setState(() => _isSaving = true);

    try {
      final notifier = ref.read(dentalLabListProvider.notifier);

      if (widget.initialCase == null) {
        // Create
        final created = await notifier.createCase(
          patientId: _selectedPatient!.id,
          caseNumber: _caseNumberController.text.trim(),
          caseType: _caseTypeController.text.trim(),
          sentDate: _sentDate,
          remarks: _remarksController.text.trim().isEmpty ? null : _remarksController.text.trim(),
        );
        if (mounted) {
          Navigator.of(context).pop(created);
        }
      } else {
        // Update
        final updated = await notifier.updateCase(
          id: widget.initialCase!.id,
          caseType: _caseTypeController.text.trim(),
          sentDate: _sentDate,
          readyDate: _readyDate,
          deliveredDate: _deliveredDate,
          remarks: _remarksController.text.trim().isEmpty ? null : _remarksController.text.trim(),
        );
        if (mounted) {
          Navigator.of(context).pop(updated);
        }
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _errorMessage = e.toString().replaceAll('Exception:', '').trim();
          _isSaving = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final isEditing = widget.initialCase != null;
    final dentalPatientsAsync = ref.watch(patientsByDepartmentProvider('dental'));
    final allPatientsAsync = ref.watch(patientsProvider);
    final dentalPatients = (dentalPatientsAsync.valueOrNull ??
            allPatientsAsync.valueOrNull ??
            [])
        .where((p) => p.department?.toLowerCase() == 'dental')
        .toList();

    final dialogConstraints = AdaptiveDialogShell.constraintsFor(
      context,
      maxMobileWidth: AppBreakpoints.maxDialogWidthMobile,
      maxTabletWidth: 540.0,
      maxDesktopWidth: 560.0,
    );

    return Dialog(
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(AppSpacing.radiusLg),
      ),
      insetPadding: const EdgeInsets.symmetric(
        horizontal: AppSpacing.md,
        vertical: AppSpacing.lg,
      ),
      child: ConstrainedBox(
        constraints: BoxConstraints(
          maxWidth: dialogConstraints.maxWidth,
          maxHeight: dialogConstraints.maxHeight,
        ),
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(AppSpacing.lg),
          child: Form(
            key: _formKey,
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              mainAxisSize: MainAxisSize.min,
              children: [
                // ── Header ───────────────────────────────────────────────
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Expanded(
                      child: Row(
                        children: [
                          Container(
                            padding: const EdgeInsets.all(8),
                            decoration: BoxDecoration(
                              color: AppColors.primaryContainer.withValues(alpha: 0.2),
                              borderRadius: BorderRadius.circular(8),
                            ),
                            child: const Icon(
                              Icons.biotech,
                              color: AppColors.primary,
                              size: 22,
                            ),
                          ),
                          const SizedBox(width: AppSpacing.sm),
                          Expanded(
                            child: Text(
                              isEditing ? 'Edit Dental Lab Case' : 'New Dental Lab Case',
                              style: AppTypography.headlineMd.copyWith(
                                fontWeight: FontWeight.bold,
                              ),
                              overflow: TextOverflow.ellipsis,
                            ),
                          ),
                        ],
                      ),
                    ),
                    IconButton(
                      icon: const Icon(Icons.close),
                      onPressed: () => Navigator.of(context).pop(),
                    ),
                  ],
                ),
                const SizedBox(height: AppSpacing.md),
                if (_errorMessage != null) ...[
                  Container(
                    padding: const EdgeInsets.all(AppSpacing.sm),
                    decoration: BoxDecoration(
                      color: AppColors.errorContainer.withValues(alpha: 0.3),
                      borderRadius: BorderRadius.circular(AppSpacing.radiusSm),
                      border: Border.all(color: AppColors.error),
                    ),
                    child: Row(
                      children: [
                        const Icon(Icons.error_outline, color: AppColors.error, size: 20),
                        const SizedBox(width: AppSpacing.xs),
                        Expanded(
                          child: Text(
                            _errorMessage!,
                            style: AppTypography.bodySm.copyWith(color: AppColors.error),
                          ),
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: AppSpacing.md),
                ],

                // ── Patient Selector ──────────────────────────────────────
                Text('PATIENT *', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                const SizedBox(height: 6),
                if (widget.preselectedPatient != null || (isEditing && _selectedPatient != null))
                  Container(
                    padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
                    decoration: BoxDecoration(
                      color: AppColors.surfaceContainerLow,
                      borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                      border: Border.all(color: AppColors.outlineVariant),
                    ),
                    child: Row(
                      children: [
                        const Icon(Icons.person, color: AppColors.primary, size: 20),
                        const SizedBox(width: AppSpacing.xs),
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Text(
                                _selectedPatient!.name,
                                style: AppTypography.bodyMd.copyWith(fontWeight: FontWeight.w600),
                              ),
                              Text(
                                'ID: ${_selectedPatient!.patientNumber} • Mobile: ${_selectedPatient!.mobile ?? "None"}',
                                style: AppTypography.bodySm.copyWith(color: AppColors.onSurfaceVariant),
                              ),
                            ],
                          ),
                        ),
                        Container(
                          padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                          decoration: BoxDecoration(
                            color: AppColors.primaryContainer.withValues(alpha: 0.15),
                            borderRadius: BorderRadius.circular(4),
                          ),
                          child: Text(
                            'Linked',
                            style: AppTypography.labelCaps.copyWith(color: AppColors.primary, fontSize: 10),
                          ),
                        ),
                      ],
                    ),
                  )
                else ...[
                  Autocomplete<PatientModel>(
                    displayStringForOption: (patient) => '${patient.name} (${patient.patientNumber})',
                    optionsBuilder: (TextEditingValue textEditingValue) {
                      if (textEditingValue.text.isEmpty) {
                        return dentalPatients.take(15);
                      }
                      final query = textEditingValue.text.toLowerCase();
                      return dentalPatients.where((patient) {
                        return patient.name.toLowerCase().contains(query) ||
                            patient.patientNumber.toLowerCase().contains(query) ||
                            (patient.mobile != null && patient.mobile!.contains(query));
                      });
                    },
                    onSelected: (patient) {
                      setState(() {
                        _selectedPatient = patient;
                      });
                    },
                    optionsViewBuilder: (context, onSelected, options) {
                      return Align(
                        alignment: Alignment.topLeft,
                        child: Material(
                          elevation: 4,
                          borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                          child: ConstrainedBox(
                            constraints: const BoxConstraints(maxHeight: 200, maxWidth: 360),
                            child: ListView.builder(
                              padding: EdgeInsets.zero,
                              shrinkWrap: true,
                              itemCount: options.length,
                              itemBuilder: (context, i) {
                                final option = options.elementAt(i);
                                return ListTile(
                                  dense: true,
                                  leading: const Icon(Icons.person, size: 18),
                                  title: Text(option.name, style: AppTypography.bodyMd),
                                  subtitle: Text(
                                    'ID: ${option.patientNumber} • ${option.mobile ?? "No phone"}',
                                    style: AppTypography.bodySm,
                                  ),
                                  onTap: () => onSelected(option),
                                );
                              },
                            ),
                          ),
                        ),
                      );
                    },
                    fieldViewBuilder: (context, controller, focusNode, onFieldSubmitted) {
                      return TextFormField(
                        controller: controller,
                        focusNode: focusNode,
                        decoration: InputDecoration(
                          hintText: 'Search patient by name, ID or mobile...',
                          prefixIcon: const Icon(Icons.search, size: 20),
                          border: OutlineInputBorder(
                            borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                          ),
                          contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                          suffixIcon: _selectedPatient != null
                              ? IconButton(
                                  icon: const Icon(Icons.clear, size: 18),
                                  onPressed: () {
                                    controller.clear();
                                    setState(() => _selectedPatient = null);
                                  },
                                )
                              : null,
                        ),
                        validator: (value) {
                          if (_selectedPatient == null) {
                            return 'Please search and select a patient';
                          }
                          return null;
                        },
                      );
                    },
                  ),
                  if (dentalPatientsAsync.isLoading && dentalPatients.isEmpty)
                    Padding(
                      padding: const EdgeInsets.only(top: 4),
                      child: Text(
                        'Loading dental patients...',
                        style: AppTypography.bodySm.copyWith(color: AppColors.onSurfaceVariant),
                      ),
                    ),
                  if (dentalPatientsAsync.hasError && dentalPatients.isEmpty)
                    Padding(
                      padding: const EdgeInsets.only(top: 4),
                      child: Row(
                        children: [
                          Text(
                            'Failed to load patients. ',
                            style: AppTypography.bodySm.copyWith(color: AppColors.error),
                          ),
                          InkWell(
                            onTap: () {
                              ref.invalidate(patientsByDepartmentProvider('dental'));
                              ref.invalidate(patientsProvider);
                            },
                            child: Text(
                              'Retry',
                              style: AppTypography.bodySm.copyWith(
                                color: AppColors.primary,
                                fontWeight: FontWeight.bold,
                              ),
                            ),
                          ),
                        ],
                      ),
                    ),
                ],

                const SizedBox(height: AppSpacing.md),

                // ── Case Number & Case Type Row ────────────────────────────
                ResponsiveFormRow(
                  breakpoint: 480,
                  flexes: const [4, 5],
                  children: [
                    // Case Number
                    Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('CASE NUMBER *', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                        const SizedBox(height: 6),
                        TextFormField(
                          controller: _caseNumberController,
                          readOnly: isEditing,
                          decoration: InputDecoration(
                            hintText: 'e.g. DEN-20261002-0001',
                            prefixIcon: const Icon(Icons.tag, size: 18),
                            filled: isEditing,
                            fillColor: isEditing ? AppColors.surfaceContainerLow : null,
                            border: OutlineInputBorder(
                              borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                            ),
                            contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                          ),
                          validator: (val) {
                            if (val == null || val.trim().isEmpty) {
                              return 'Required';
                            }
                            return null;
                          },
                        ),
                      ],
                    ),

                    // Case Type
                    Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('CASE TYPE *', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                        const SizedBox(height: 6),
                        TextFormField(
                          controller: _caseTypeController,
                          decoration: InputDecoration(
                            hintText: 'e.g. Zirconia Crown',
                            prefixIcon: const Icon(Icons.medical_services_outlined, size: 18),
                            border: OutlineInputBorder(
                              borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                            ),
                            contentPadding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                          ),
                          validator: (val) {
                            if (val == null || val.trim().isEmpty) {
                              return 'Required';
                            }
                            return null;
                          },
                        ),
                      ],
                    ),
                  ],
                ),

                const SizedBox(height: AppSpacing.xs),

                // Quick suggestions for Case Type
                Wrap(
                  spacing: 6,
                  runSpacing: 4,
                  children: _suggestedCaseTypes.take(6).map((type) {
                    return ActionChip(
                      label: Text(type, style: const TextStyle(fontSize: 11)),
                      padding: EdgeInsets.zero,
                      materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
                      visualDensity: VisualDensity.compact,
                      onPressed: () {
                        setState(() {
                          _caseTypeController.text = type;
                        });
                      },
                    );
                  }).toList(),
                ),

                const SizedBox(height: AppSpacing.md),

                // ── Date Pickers ──────────────────────────────────────────
                ResponsiveFormRow(
                  breakpoint: 480,
                  children: [
                    // Sent Date
                    Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('SENT DATE *', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                        const SizedBox(height: 6),
                        InkWell(
                          onTap: _pickSentDate,
                          borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                          child: Container(
                            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                            decoration: BoxDecoration(
                              border: Border.all(color: AppColors.outlineVariant),
                              borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                            ),
                            child: Row(
                              mainAxisAlignment: MainAxisAlignment.spaceBetween,
                              children: [
                                Text(
                                  DateFormat('dd MMM yyyy').format(_sentDate),
                                  style: AppTypography.bodyMd,
                                ),
                                const Icon(Icons.calendar_today, size: 16, color: AppColors.primary),
                              ],
                            ),
                          ),
                        ),
                      ],
                    ),

                    if (isEditing)
                      // Ready Date (if applicable)
                      Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('READY DATE', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                          const SizedBox(height: 6),
                          InkWell(
                            onTap: _pickReadyDate,
                            borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                            child: Container(
                              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                              decoration: BoxDecoration(
                                border: Border.all(color: AppColors.outlineVariant),
                                borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                              ),
                              child: Row(
                                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                children: [
                                  Text(
                                    _readyDate != null ? DateFormat('dd MMM yyyy').format(_readyDate!) : 'Not set',
                                    style: AppTypography.bodyMd.copyWith(
                                      color: _readyDate != null ? AppColors.onSurface : AppColors.onSurfaceVariant,
                                    ),
                                  ),
                                  const Icon(Icons.event_available, size: 16, color: AppColors.secondary),
                                ],
                              ),
                            ),
                          ),
                        ],
                      ),

                    if (isEditing)
                      // Delivered Date (if applicable)
                      Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('DELIVERED DATE', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                          const SizedBox(height: 6),
                          InkWell(
                            onTap: _pickDeliveredDate,
                            borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                            child: Container(
                              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
                              decoration: BoxDecoration(
                                border: Border.all(color: AppColors.outlineVariant),
                                borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                              ),
                              child: Row(
                                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                children: [
                                  Text(
                                    _deliveredDate != null ? DateFormat('dd MMM yyyy').format(_deliveredDate!) : 'Not set',
                                    style: AppTypography.bodyMd.copyWith(
                                      color: _deliveredDate != null ? AppColors.onSurface : AppColors.onSurfaceVariant,
                                    ),
                                  ),
                                  const Icon(Icons.done_all, size: 16, color: Colors.green),
                                ],
                              ),
                            ),
                          ),
                        ],
                      ),
                  ],
                ),

                const SizedBox(height: AppSpacing.md),

                // ── Remarks ───────────────────────────────────────────────
                Text('REMARKS / INSTRUCTIONS', style: AppTypography.labelCaps.copyWith(color: AppColors.onSurfaceVariant)),
                const SizedBox(height: 6),
                TextFormField(
                  controller: _remarksController,
                  maxLines: 2,
                  decoration: InputDecoration(
                    hintText: 'e.g. Shade A2, 0.5mm subgingival margin, urgent case...',
                    border: OutlineInputBorder(
                      borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                    ),
                    contentPadding: const EdgeInsets.all(12),
                  ),
                ),
                const SizedBox(height: AppSpacing.lg),
                // ── Actions ────────────────────────────────────────────────
                Wrap(
                  alignment: WrapAlignment.end,
                  spacing: AppSpacing.sm,
                  runSpacing: AppSpacing.xs,
                  children: [
                    TextButton(
                      onPressed: _isSaving ? null : () => Navigator.of(context).pop(),
                      child: const Text('Cancel'),
                    ),
                    FilledButton.icon(
                      onPressed: _isSaving ? null : _save,
                      icon: _isSaving
                          ? const SizedBox(width: 16, height: 16, child: CircularProgressIndicator(strokeWidth: 2, color: Colors.white))
                          : const Icon(Icons.check, size: 18),
                      label: Text(isEditing ? 'Save Changes' : 'Create Lab Case'),
                    ),
                  ],
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
